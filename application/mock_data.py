"""
Schema driven mock data.

Rows are generated by walking a model's leaf fields (the same walk that maps
CSV columns onto the model, see ``models.logic.pydantic_helper``). For every
leaf a provider is looked up by ``"<Model>.<field>"`` (following the model's
MRO and the model a reordered variant was derived from), then by field name,
then by the field type. Values honour the active validation settings (allowed
authorities, country/currency codes, declaration types, date formats...).

Every generated row is validated with the real model before it is returned,
so a schema or settings change the generator does not know about fails loudly
instead of producing data that will not load.

The data is deliberately recognisable as fake: fictional names and places,
identifiers starting with TEST / MOCK, document serials from the 990000+ range.
Only what validation or routing depends on (codes, formats, dates, routing
keywords) looks real. Never seed it from real exports.
"""

import csv
import random
import types
from dataclasses import dataclass, field
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Callable, Iterable, Optional, Union, get_args, get_origin

from pydantic import BaseModel, ValidationError

from application.configuration_handling import settings as default_settings
from models.declaration import DeclarationUpdates
from models.logic.pydantic_helper import LeafField
from models.logic.validators import as_list
from models.registry import PAPER_KINDS, PaperKind

COMPANY_FORMS = ["LLC", "JSC", "PJSC", "SE", "PE"]
COMPANY_WORDS = [
    "Example Trading", "Sample Logistics", "Demo Metals", "Test Agro", "Placeholder Freight", "Fictional Fuels",
    "Mock Machinery", "Dummy Foods", "Specimen Chemicals", "Prototype Textiles", "Example Grain", "Sample Steel",
]
# "Testov", "Primerova" (primer = example), "Obraztsov" (obrazets = sample), "Demova": fictional by construction.
PERSON_NAMES = ["Testov Ivan Ivanovich", "Primerova Anna Petrovna", "Obraztsov Pavel Sergeevich", "Demova Olga Nikolaevna"]
CITIES = [("000101", "Testville"), ("000202", "Sampleton"), ("000303", "Exampleburg"), ("000404", "Demo City"),
          ("000505", "Mockford"), ("000606", "Placeholder Bay")]
STREETS = ["1st Example St.", "Sample Ave.", "Test Lane", "Demo Blvd.", "Mock Rd.", "Placeholder Sq.", "Fiction St.",
           "Specimen Ave."]
COUNTRY_NAMES = {"RU": "RUSSIA", "BY": "BELARUS", "CN": "CHINA", "TR": "TURKEY", "DE": "GERMANY",
                 "KZ": "KAZAKHSTAN", "IT": "ITALY", "AM": "ARMENIA", "UZ": "UZBEKISTAN", "IN": "INDIA"}
GOODS = [("Graphics tablet", "8471607000"), ("Compound feed", "2309909610"),
         ("Crude oil", "2709009001"), ("Flat-rolled iron products", "7208390000"),
         ("Nitrogen fertilisers", "3102101000"), ("Soft wheat", "1001990000"),
         ("Hard coal", "2701121000"), ("Heating fuel oil", "2710196200")]
BANKS = ["Example Settlement Bank", "Sample Reserve Bank", "Test Commercial Bank", "Demo Savings Bank"]
# Serials of generated declaration / statement numbers: far above real daily volumes, so a mock number
# built from a real authority code and date does not coincide with a real document.
MOCK_SERIALS = (990_000, 999_999)
RATES = {"RUB": 1.0, "USD": 92.15, "EUR": 99.4, "CNY": 12.7, "BYN": 28.3, "KZT": 0.19}
# Routed by the re_for_* patterns, which match the Russian wording of the source data,
# so these stay in Russian: sale, export, import, temporary return, processing.
STATED_GOALS = ["Реализация", "Экспорт", "Импорт", "Временный возврат", "Переработка"]
DOCUMENT_CODES = ["4011", "4021", "2011", "5011", "9999"]
PROCEDURES = ["400000", "100000", "401000", "310000"]

# Additional entities are usually empty in the source files.
BLANKABLE_GROUPS = {"sender_additional", "receiver_additional", "financially_responsibe_additional"}

# One field per kind that is broken on purpose to produce invalid rows.
INVALID_VALUES = {
    "declaration": ("declaration_id", "700WRONGCODE/WRONG0/CODE00"),
    "declarationupdates": ("declaration_id", "700WRONGCODE/WRONG0/CODE00"),
    "clearancestatement": ("statement_date", "31.02.2021"),
    "waybill": ("registration", "32.13.2022"),
}


@dataclass
class Context:
    rng: random.Random
    kind: PaperKind
    leaf: LeafField
    date: datetime  # document date shared by the row
    state: dict = field(default_factory=dict)

    @property
    def group(self) -> str:
        return self.leaf.path[0]


Provider = Callable[[Context], str]


class MockDataGenerator:
    def __init__(self, seed: Optional[int] = None, settings=default_settings, max_age_days: int = 720):
        self.rng = random.Random(seed)
        self.settings = settings
        self.max_age_days = max_age_days
        s = settings
        self.authorities = as_list(s.authority_allow_list) or ["700000000"]
        alpha2 = [code for code in as_list(s.alpha2_codes) if len(code) == 2 and code.isupper()]
        self.countries = [code for code in COUNTRY_NAMES if code in alpha2] or alpha2 or ["RU"]
        currencies = as_list(s.allowed_currency_codes)
        self.currencies = [code for code in RATES if code in currencies] or currencies[:3]
        self.declaration_types = as_list(s.declaration_types_allow_list) or ["ИМ40", "ЭК10"]
        self.statement_modes = as_list(s.statement_mode)
        crud = s.declaration_crud_allow_dict
        self.crud_create = as_list(crud.get("create")) or ["main"]
        self.crud_update = [v for k, vs in crud.items() if k != "create" for v in as_list(vs)] or ["korrekt"]
        self.feacn_length = int(s.feacn_length)
        self.providers = self._providers()

    # ------------------------------------------------------------------ helpers
    def _digits(self, n: int) -> str:
        return str(self.rng.randint(1, 9)) + "".join(str(self.rng.randint(0, 9)) for _ in range(n - 1))

    def _test_id(self, n: int = 6) -> str:
        """Tax / bank identifiers: never a real one."""
        return "TEST" + self._digits(n)

    def _serial(self) -> str:
        return f"{self.rng.randint(*MOCK_SERIALS):06d}"

    def _company(self) -> str:
        if self.rng.random() < 0.1:
            return "SP " + self.rng.choice(PERSON_NAMES).upper()
        return f'{self.rng.choice(COMPANY_FORMS)} "{self.rng.choice(COMPANY_WORDS).upper()}"'

    def _address(self) -> str:
        index, city = self.rng.choice(CITIES)
        return f"{index}, {city}, {self.rng.choice(STREETS)}, bld. {self.rng.randint(1, 120)}"

    def _amount(self, low=1_000, high=5_000_000) -> float:
        return round(self.rng.uniform(low, high), 2)

    def _goods(self, ctx: Context) -> tuple[str, str]:
        return ctx.state.setdefault("goods", self.rng.choice(GOODS))

    def _currency(self, ctx: Context) -> str:
        return ctx.state.setdefault("currency", self.rng.choice(self.currencies))

    def _country(self, ctx: Context) -> str:
        return ctx.state.setdefault(f"country:{ctx.group}", self.rng.choice(self.countries))

    def _later(self, moment: datetime, max_days: int = 30) -> datetime:
        return moment + timedelta(days=self.rng.randint(0, max_days), seconds=self.rng.randint(0, 86_399))

    def _document_dates(self, ctx: Context) -> tuple[datetime, Optional[datetime]]:
        if "doc_dates" not in ctx.state:
            started = ctx.date - timedelta(days=self.rng.randint(30, 400))
            ended = None if self.rng.random() < 0.15 else started + timedelta(days=self.rng.randint(1, 1000))
            ctx.state["doc_dates"] = (started, ended)
        return ctx.state["doc_dates"]

    def _feacn(self, ctx: Context) -> str:
        return self._goods(ctx)[1][: self.feacn_length].ljust(self.feacn_length, "0")

    # ---------------------------------------------------------------- providers
    def _providers(self) -> dict[str, Provider]:
        r = self.rng
        return {
            # Declaration
            "Declaration.crud_type": lambda c: r.choice(
                self.crud_update if issubclass(c.kind.model, DeclarationUpdates) else self.crud_create
            ),
            "Declaration.op_type": lambda c: r.choice(self.declaration_types),
            "Declaration.declaration_id": lambda c: (
                f"{r.choice(self.authorities)}/{c.date:%d%m%y}/{self._serial()}"
            ),
            "Declaration.value_in_rub": lambda c: f"{c.state.setdefault('amount', self._amount()) * RATES.get(self._currency(c), 1.0):.2f}",
            "Declaration.timestamp": lambda c: f"{self._later(c.date):%d.%m.%Y %H:%M:%S}",
            # Entities / countries / money / banks
            "Entity.tax_payer_id": lambda c: "" if r.random() < 0.1 else self._test_id(r.choice([6, 8])),
            "Entity.name": lambda c: self._company(),
            "Entity.address": lambda c: self._address(),
            "Country.name": lambda c: COUNTRY_NAMES.get(self._country(c), "UNKNOWN"),
            "Country.code": lambda c: self._country(c),
            "InvoiceAmount.value": lambda c: f"{c.state.setdefault('amount', self._amount()):.2f}",
            "InvoiceAmount.currency_alpha3": lambda c: self._currency(c),
            "InvoiceAmount.exchange_rate": lambda c: f"{RATES.get(self._currency(c), 1.0):g}",
            "Bank.sort_code": lambda c: self._test_id(),
            "Bank.name": lambda c: r.choice(BANKS),
            "Bank.classifier": lambda c: self._test_id(),
            # Items and their documents
            "Item.feacn_code": self._feacn,
            "Item.procedure": lambda c: r.choice(PROCEDURES),
            "Item.parent": lambda c: "",
            "Item.item_price": lambda c: f"{c.state.setdefault('amount', self._amount()):.2f}",
            "Document.document_code": lambda c: r.choice(DOCUMENT_CODES),
            "Document.document": lambda c: f"{self._document_dates(c)[0]:%Y/%m/%d}",
            "Document.date_started": lambda c: f"{self._document_dates(c)[0]:%d/%m/%y}",
            "Document.date_ended": lambda c: (
                "" if self._document_dates(c)[1] is None else f"{self._document_dates(c)[1]:%d/%m/%y}"
            ),
            # Clearance statements
            "ClearanceStatement.statement_id": lambda c: (
                f"{r.choice(self.authorities)}/{c.date:%Y}/{self._serial()}"
            ),
            "ClearanceStatement.statement_date": lambda c: f"{c.date:%d.%m.%Y}",
            "ClearanceStatement.mode_of_operation": lambda c: r.choice(self.statement_modes),
            "ClearanceStatement.item_name": lambda c: f"{self._goods(c)[0]}, Qty - {r.randint(1, 50)} pcs.",
            "ClearanceStatement.feacn_code": self._feacn,
            "ClearanceStatement.cost_in_rubles": lambda c: f"{c.state.setdefault('amount', self._amount(100, 90_000)) * RATES.get(self._currency(c), 1.0):.2f}",
            "ClearanceStatement.item_weight": lambda c: f"{r.uniform(0.1, 900):.2f}",
            "ClearanceStatement.delivery_contract": lambda c: f"No. {r.randint(1, 99)}/{c.date:%m}-{c.date:%Y} of {c.date - timedelta(days=90):%d.%m.%Y}",
            "ClearanceStatement.waybill": lambda c: f"CMR No. {r.randint(1, 999)} of {c.date - timedelta(days=5):%d.%m.%Y}",
            "ClearanceStatement.commercial_finance_documents": lambda c: f"Invoice No. {r.randint(1, 999)} of {c.date - timedelta(days=7):%d.%m.%Y}",
            "ClearanceStatement.other_documents": lambda c: f"Packing list No. {r.randint(1, 999)}",
            "ClearanceStatement.released_at": lambda c: f"{self._later(c.date, 2):%Y-%m-%d %H:%M:%S}",
            # Waybills
            "Waybill.id": lambda c: f"MOCK-{r.randint(1, 99_999)}",
            "Waybill.registration": lambda c: f"{c.date:%d.%m.%Y}",
            "Waybill.stated_goal": lambda c: r.choice(STATED_GOALS),
            "Waybill.crossed_at": lambda c: f"{self._later(c.date, 5):%d.%m.%Y}",
            "Waybill.contract": lambda c: f"{r.randint(1, 99)}/{c.date:%y} of {c.date - timedelta(days=200):%d.%m.%Y}",
            "Waybill.specification": lambda c: f"{r.randint(1, 20)} of {c.date - timedelta(days=30):%d.%m.%Y}",
            "Waybill.seller_bank": lambda c: self._test_id(),
            "Waybill.buyer_bank": lambda c: self._test_id(),
            "Waybill.sender_name": lambda c: self._company(),
            "Waybill.receiver_name": lambda c: self._company(),
            "Waybill.sender_tax_payer_id": lambda c: self._test_id(),
            "Waybill.receiver_tax_payer_id": lambda c: self._test_id(),
            "Waybill.sender_cargo_handling_terminal": lambda c: self._address(),
            "Waybill.receiver_cargo_handling_terminal": lambda c: self._address(),
            "Waybill.currency": lambda c: self._currency(c),
            "Waybill.item_name": lambda c: self._goods(c)[0],
            "Waybill.price_in_national_currency": lambda c: f"{c.state.setdefault('amount', self._amount()):.2f}",
            "Waybill.correction_date": lambda c: "" if r.random() < 0.8 else f"{self._later(c.date):%d.%m.%Y}",
            "Waybill.global_unique_identifier": lambda c: "%064X" % r.getrandbits(256),
        }

    def _owner_names(self, model: type[BaseModel]) -> Iterable[str]:
        while model is not None:
            for cls in model.__mro__:
                if isinstance(cls, type) and issubclass(cls, BaseModel) and cls is not BaseModel:
                    yield cls.__name__
            model = getattr(model, "__source_model__", None)

    def _by_type(self, ctx: Context) -> str:
        annotation = ctx.leaf.info.annotation
        args = get_args(annotation) if get_origin(annotation) in (Union, types.UnionType) else (annotation,)
        if float in args:
            return f"{self._amount():.2f}"
        if int in args:
            return self._digits(6)
        return f"{ctx.leaf.name} {self.rng.randint(1, 9999)}"

    def value(self, ctx: Context) -> str:
        for owner in self._owner_names(ctx.leaf.owner):
            provider = self.providers.get(f"{owner}.{ctx.leaf.name}")
            if provider is not None:
                return provider(ctx)
        provider = self.providers.get(ctx.leaf.name, self._by_type)
        return provider(ctx)

    # -------------------------------------------------------------------- rows
    def _raw_row(self, kind: PaperKind) -> list[str]:
        date = datetime.now() - timedelta(days=self.rng.randint(0, self.max_age_days))
        blank = {group for group in BLANKABLE_GROUPS if self.rng.random() < 0.75}
        state: dict = dict()
        row = list()
        for leaf in kind.model.leaf_fields():
            if leaf.path[0] in blank:
                row.append("")
            else:
                row.append(self.value(Context(rng=self.rng, kind=kind, leaf=leaf, date=date, state=state)))
        return row

    def valid_row(self, kind: PaperKind, attempts: int = 25) -> list[str]:
        error = None
        for _ in range(attempts):
            row = self._raw_row(kind)
            try:
                kind.model.from_row(row)
                return row
            except ValidationError as e:
                error = e
        raise RuntimeError(
            f"Could not generate a valid {kind.title} row, the generator is out of date with the "
            f"schema/settings:\n{error}"
        )

    def invalid_row(self, kind: PaperKind) -> list[str]:
        row = self.valid_row(kind)
        column, bad_value = INVALID_VALUES[kind.key]
        index = [leaf.column for leaf in kind.model.leaf_fields()].index(column)
        row[index] = bad_value
        try:
            kind.model.from_row(row)
        except ValidationError:
            return row
        raise RuntimeError(f"{kind.title}: {column}={bad_value!r} unexpectedly passed validation")

    def rows(self, kind: PaperKind, count: int, invalid_ratio: float = 0.0) -> list[list[str]]:
        invalid = round(count * invalid_ratio)
        rows = [self.invalid_row(kind) for _ in range(invalid)] + [self.valid_row(kind) for _ in range(count - invalid)]
        self.rng.shuffle(rows)
        return rows

    def documents(self, kind: PaperKind, count: int) -> list[dict]:
        """Validated documents, as they are stored by the pipeline."""
        return [kind.model.from_row(self.valid_row(kind)).model_dump(mode="json") for _ in range(count)]

    # ------------------------------------------------------------------ output
    def write_csv(
        self, directory: Union[str, Path], kind: PaperKind, count: int, invalid_ratio: float = 0.0, delimiter: str = "^"
    ) -> Path:
        directory = Path(directory)
        directory.mkdir(parents=True, exist_ok=True)
        stamp = datetime.now().strftime("%Y%m%d_%H%M%S_%f")
        path = directory / f"{kind.file_prefix}mock_{stamp}.csv"
        with path.open("w", encoding="utf-8", newline="") as handle:
            # Same layout as the real exports: no quoting, quotes are part of the values.
            writer = csv.writer(handle, delimiter=delimiter, quoting=csv.QUOTE_NONE, quotechar=None, lineterminator="\n")
            writer.writerow(kind.model.flat_titles())
            writer.writerows(self.rows(kind, count, invalid_ratio))
        return path

    def seed_repository(self, repository, kind: PaperKind, count: int, days: int) -> int:
        """Insert documents straight into storage, spread over the last ``days`` days."""
        now = datetime.now(timezone.utc)
        inserted = 0
        for document in self.documents(kind, count):
            created_at = now - timedelta(seconds=self.rng.randint(0, max(days, 1) * 86_400 - 1))
            inserted += repository.insert_many(kind.key, [document], created_at=created_at)
        return inserted


def kinds_from_names(names: Optional[Iterable[str]]) -> list[PaperKind]:
    if not names:
        return list(PAPER_KINDS)
    by_key = {kind.key: kind for kind in PAPER_KINDS}
    try:
        return [by_key[name] for name in names]
    except KeyError as e:
        raise ValueError(f"unknown kind {e}, expected: {', '.join(by_key)}") from None
